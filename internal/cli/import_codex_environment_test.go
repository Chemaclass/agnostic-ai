const appEnvironmentTOML = `# THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY
version = 1
name = "Acme"

[setup]
script = "bash scripts/setup-worktree.bash"

[cleanup]
script = "bash scripts/stop-preview.bash"

[[actions]]
name = "Dashboard"
icon = "run"
command = "bash scripts/run-preview.bash"

[[actions]]
name = "Tests"
icon = "test"
command = '''
go test ./...
go vet ./...
'''
`

// A hand-written .codex/environments/environment.toml becomes an
// environment spec (#1393).
func TestImportFromCodex_ReadsEnvironmentTOML(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, ".codex", "environments", "environment.toml"), appEnvironmentTOML)
	if err := importFromCodex(dir, rootSources()); err != nil {
		t.Fatal(err)
	}
	got := readFileString(t, filepath.Join(dir, "environments", "codex.yaml"))
	want := `name: Acme
setup: bash scripts/setup-worktree.bash
cleanup: bash scripts/stop-preview.bash
dev-commands:
    - name: Dashboard
      command: bash scripts/run-preview.bash
    - name: Tests
      command: |-
        go test ./...
        go vet ./...
      icon: test
`
	if got != want {
		t.Errorf("environments/codex.yaml:\n%s\nwant:\n%s", got, want)
	}
}


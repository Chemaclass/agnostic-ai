// The cd that sync writes for a dev command's cwd imports back as cwd.
func TestImportFromCodex_ReadsActionCwd(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, ".codex", "environments", "environment.toml"), `version = 1
name = "web"

[[actions]]
name = "Docs"
icon = "run"
command = "cd apps/docs && pnpm dev"

[[actions]]
name = "Site"
icon = "run"
command = "cd 'my site' && npm start"

[[actions]]
name = "Seed"
icon = "run"
command = """
cd api || exit 1
npm run seed
"""
`)
	if err := importFromCodex(dir, rootSources()); err != nil {
		t.Fatal(err)
	}
	got := readFileString(t, filepath.Join(dir, "environments", "codex.yaml"))
	want := `name: web
dev-commands:
    - name: Docs
      command: pnpm dev
      cwd: apps/docs
    - name: Site
      command: npm start
      cwd: my site
    - name: Seed
      command: npm run seed
      cwd: api
`
	if got != want {
		t.Errorf("environments/codex.yaml:\n%s\nwant:\n%s", got, want)
	}
}

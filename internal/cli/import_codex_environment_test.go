// import, then sync, writes an environment.toml with the same scripts and
// actions, and the other targets get their files from the same spec.
func TestImportFromCodex_EnvironmentTOMLSurvivesSync(t *testing.T) {
	dir := t.TempDir()
	testutil.Chdir(t, dir)
	silence(t)
	captureLogOut(t)
	writeFile(t, "agnostic-ai.yaml", "version: 1\ntargets: [codex, cursor, claude]\n")
	writeFile(t, filepath.Join(".codex", "environments", "environment.toml"), appEnvironmentTOML)

	for _, args := range [][]string{{"import", "codex"}, {"sync"}, {"sync", "--check"}} {
		root := NewRootCmd("test")
		root.SetArgs(args)
		if err := root.Execute(); err != nil {
			t.Fatalf("%v: %v", args, err)
		}
	}
	got := readFile(t, filepath.Join(".codex", "environments", "environment.toml"))
	for _, want := range []string{
		"name = \"Acme\"\n",
		"[setup]\nscript = \"bash scripts/setup-worktree.bash\"\n",
		"[cleanup]\nscript = \"bash scripts/stop-preview.bash\"\n",
		"[[actions]]\nname = \"Dashboard\"\nicon = \"run\"\ncommand = \"bash scripts/run-preview.bash\"\n",
		"name = \"Tests\"\nicon = \"test\"\ncommand = \"\"\"\ngo test ./...\ngo vet ./...\n\"\"\"\n",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("synced environment.toml misses %q:\n%s", want, got)
		}
	}
	if _, err := os.Stat(filepath.Join(".claude", "launch.json")); err != nil {
		t.Errorf("the same spec did not reach .claude/launch.json: %v", err)
	}
}

// A file sync wrote, an existing spec, and a key the spec cannot hold all
// leave the file alone.
func TestImportFromCodex_LeavesEnvironmentTOMLItCannotHold(t *testing.T) {
	cases := map[string]string{
		"a darwin script":    "version = 1\nname = \"a\"\n[setup]\nscript = \"x\"\n[setup.darwin]\nscript = \"y\"\n",
		"an action platform": "version = 1\nname = \"a\"\n[[actions]]\nname = \"Run\"\ncommand = \"x\"\nplatform = \"darwin\"\n",
		"a windows cleanup":  "version = 1\nname = \"a\"\n[cleanup]\nscript = \"x\"\n[cleanup.win32]\nscript = \"y\"\n",
		"an unknown key":     "version = 1\nname = \"a\"\nextra = 1\n",
		"a repeated action":  "version = 1\nname = \"a\"\n[[actions]]\nname = \"Run\"\ncommand = \"x\"\n[[actions]]\nname = \"Run\"\ncommand = \"y\"\n",
	}
	for name, body := range cases {
		dir := t.TempDir()
		writeFile(t, filepath.Join(dir, ".codex", "environments", "environment.toml"), body)
		if err := importFromCodex(dir, rootSources()); err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if _, err := os.Stat(filepath.Join(dir, "environments", "codex.yaml")); !os.IsNotExist(err) {
			t.Errorf("%s: the file was imported: %v", name, err)
		}
	}

	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, ".codex", "environments", "environment.toml"), appEnvironmentTOML)
	own := "name: mine\nsetup: make other\n"
	writeFile(t, filepath.Join(dir, "environments", "codex.yaml"), own)
	if err := importFromCodex(dir, rootSources()); err != nil {
		t.Fatal(err)
	}
	if got := readFileString(t, filepath.Join(dir, "environments", "codex.yaml")); got != own {
		t.Errorf("existing spec changed:\n%s", got)
	}

	synced := t.TempDir()
	writeFile(t, filepath.Join(synced, ".codex", "environments", "environment.toml"), appEnvironmentTOML)
	writeFile(t, filepath.Join(synced, ".agnostic-ai", ".sync-state"), `{"outputs":[".codex/environments/environment.toml"]}`)
	if err := importFromCodex(synced, rootSources()); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(synced, "environments", "codex.yaml")); !os.IsNotExist(err) {
		t.Errorf("a synced environment.toml was imported: %v", err)
	}
}


func TestImportFromCodex_AgnosticEmittedFormat(t *testing.T) {
	// Round-trip: AGENTS.md generated by our codex adapter, with the
	// "## Conventions" wrapper, "Generated by agnostic-ai" header, and
	// per-rule italic descriptions.
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "AGENTS.md"), `# AGENTS.md

Generated by agnostic-ai. Do not edit by hand.

## Conventions

### conventional-commits

_Always use Conventional Commits._

Use feat:, fix:, etc.

### go-style

_gofmt-clean code._

No init() functions in business code.
`)
	if err := importFromCodex(dir); err != nil {
		t.Fatal(err)
	}

	got, err := os.ReadFile(filepath.Join(dir, "rules", "conventional-commits.md"))
	if err != nil {
		t.Fatal(err)
	}
	out := string(got)
	for _, want := range []string{
		"name: conventional-commits",
		"description: Always use Conventional Commits.",
		"Use feat:, fix:, etc.",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("expected %q in:\n%s", want, out)
		}
	}
	// Italic line should not leak into the body.
	if strings.Contains(out, "_Always use Conventional Commits._") {
		t.Errorf("italic description leaked into body:\n%s", out)
	}
	// Boilerplate header should not become a rule.
	if _, err := os.Stat(filepath.Join(dir, "rules", "agents-md.md")); err == nil {
		t.Error("did not expect a rule from the # AGENTS.md header")
	}
}

func TestImportFromCodex_AggressiveItalicExtraction(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "AGENTS.md"), `## rule-a

_Short desc._

Body of A.

## rule-b

_Multi
line italic._

Body of B.

## rule-c

Plain body, no italic.
`)
	if err := importFromCodex(dir); err != nil {
		t.Fatal(err)
	}

	a, _ := os.ReadFile(filepath.Join(dir, "rules", "rule-a.md"))
	if !strings.Contains(string(a), "description: Short desc.") {
		t.Errorf("rule-a missing description, got:\n%s", a)
	}
	if strings.Contains(string(a), "_Short desc._") {
		t.Errorf("rule-a italic leaked into body:\n%s", a)
	}

	// Multi-line italic does not match — only a single-line _..._ qualifies.
	b, _ := os.ReadFile(filepath.Join(dir, "rules", "rule-b.md"))
	if strings.Contains(string(b), "description:") {
		t.Errorf("rule-b should have no description (multi-line italic), got:\n%s", b)
	}

	c, _ := os.ReadFile(filepath.Join(dir, "rules", "rule-c.md"))
	if strings.Contains(string(c), "description:") {
		t.Errorf("rule-c should have no description, got:\n%s", c)
	}
}

func TestImportFromCodex_NestedAgentsMdInfersGlobs(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "AGENTS.md"), "## root-rule\n\nproject-wide.\n")
	writeFile(t, filepath.Join(dir, "src", "AGENTS.md"), "## src-rule\n\nscoped to src.\n")
	writeFile(t, filepath.Join(dir, "docs", "api", "AGENTS.md"), "## api-rule\n\nscoped to docs/api.\n")

	if err := importFromCodex(dir); err != nil {
		t.Fatal(err)
	}

	root, _ := os.ReadFile(filepath.Join(dir, "rules", "root-rule.md"))
	if strings.Contains(string(root), "globs:") {
		t.Errorf("root rule should not have globs, got:\n%s", root)
	}

	src, _ := os.ReadFile(filepath.Join(dir, "rules", "src-rule.md"))
	if !strings.Contains(string(src), "globs: src/**") {
		t.Errorf("src rule missing globs: src/**, got:\n%s", src)
	}

	api, _ := os.ReadFile(filepath.Join(dir, "rules", "api-rule.md"))
	if !strings.Contains(string(api), "globs: docs/api/**") {
		t.Errorf("api rule missing globs: docs/api/**, got:\n%s", api)
	}
}


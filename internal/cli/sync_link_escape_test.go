func linkEscapeProject(t *testing.T) string {
	t.Helper()
	if runtime.GOOS == "windows" {
		t.Skip("symlinks need privileges on Windows")
	}
	globalAgentTestHome(t)
	dir := setupFixture(t)
	mustWrite(t, filepath.Join(dir, "agnostic-ai.yaml"), "version: 1\ntargets: [claude]\n")
	testutil.Chdir(t, dir)
	silence(t)
	captureLogOut(t)
	return dir
}

func mustSymlink(t *testing.T, target, link string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(link), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, link); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
}

func treeEntries(t *testing.T, root string) []string {
	t.Helper()
	var paths []string
	err := filepath.Walk(root, func(p string, _ os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		paths = append(paths, p)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return paths
}

func TestSync_RefusesAHookScriptThroughALinkIntoGitHooks(t *testing.T) {
	dir := linkEscapeProject(t)
	if err := os.MkdirAll(filepath.Join(dir, ".git", "hooks"), 0o755); err != nil {
		t.Fatal(err)
	}
	mustSymlink(t, filepath.Join("..", ".git", "hooks"), filepath.Join(dir, ".claude", "hooks"))
	script := filepath.Join(dir, ".agnostic-ai", "scripts", "post-commit")
	mustWrite(t, script, "#!/bin/sh\necho ran\n")
	if err := os.Chmod(script, 0o755); err != nil {
		t.Fatal(err)
	}
	mustWrite(t, filepath.Join(dir, ".agnostic-ai", "hooks", "run.yaml"),
		"name: run\nevent: PreToolUse\ncommand: .agnostic-ai/scripts/post-commit\n")

	err := runProjectSync()

	if err == nil || !strings.Contains(err.Error(), filepath.Join(".claude", "hooks")) {
		t.Errorf("sync must fail naming the link .claude/hooks, got %v", err)
	}
	if _, statErr := os.Lstat(filepath.Join(dir, ".git", "hooks", "post-commit")); !os.IsNotExist(statErr) {
		t.Errorf(".git/hooks/post-commit must not exist: %v", statErr)
	}
}

func TestSync_RefusesWritesThroughALinkedToolFolderOutsideTheProject(t *testing.T) {
	dir := linkEscapeProject(t)
	outside := t.TempDir()
	mustSymlink(t, outside, filepath.Join(dir, ".claude"))
	mustWrite(t, filepath.Join(dir, ".agnostic-ai", "hooks", "guard.yaml"),
		"name: guard\nevent: PreToolUse\ncommand: echo guard\n")
	before := treeEntries(t, outside)

	err := runProjectSync()

	if err == nil || !strings.Contains(err.Error(), ".claude") || !strings.Contains(err.Error(), "outside the project") {
		t.Errorf("sync must fail naming the link .claude, got %v", err)
	}
	if after := treeEntries(t, outside); strings.Join(after, "\n") != strings.Join(before, "\n") {
		t.Errorf("sync changed the folder outside the project:\nbefore %v\nafter  %v", before, after)
	}
}

func TestSync_WritesThroughALinkThatStaysInsideTheProject(t *testing.T) {
	dir := linkEscapeProject(t)
	mustSymlink(t, "AGENTS.md", filepath.Join(dir, "CLAUDE.md"))
	mustWrite(t, filepath.Join(dir, "tools", "claude", ".keep"), "")
	mustSymlink(t, filepath.Join("tools", "claude"), filepath.Join(dir, ".claude"))

	if err := runProjectSync(); err != nil {
		t.Fatalf("sync: %v", err)
	}

	if info, err := os.Lstat(filepath.Join(dir, "CLAUDE.md")); err != nil || info.Mode()&os.ModeSymlink == 0 {
		t.Errorf("CLAUDE.md must stay a link: %v", err)
	}
	if got := readFile(t, filepath.Join(dir, "AGENTS.md")); !strings.Contains(got, "Generated by agnostic-ai") {
		t.Errorf("AGENTS.md must hold the entry point written through CLAUDE.md, got:\n%s", got)
	}
	if got := readFile(t, filepath.Join(dir, "tools", "claude", "rules", "r1.md")); !strings.Contains(got, "rule body") {
		t.Errorf("the rule must land in the linked folder, got:\n%s", got)
	}
}


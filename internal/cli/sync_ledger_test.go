// A ledgered shared-skills link that became a real directory (the opt-in
// was turned off, or the folder now holds a user-owned file) is not an
// orphan file: its own files are ledgered separately. The sweep skips it
// instead of failing to read a directory and abandoning later orphans.
func TestSweepLedgerOrphans_SkipsFormerLinkNowDirectory(t *testing.T) {
	chdir(t, t.TempDir())
	const former, orphan = ".cursor/skills/greet", "z-old.md"
	mustWriteFile(t, former+"/SKILL.md", "mine\n")
	mustWriteFile(t, orphan, "<!-- Generated by agnostic-ai -->\nold\n")

	removed, _, err := sweepLedgerOrphans(adapters.NewSession(), []string{former, orphan}, nil, nil)
	if err != nil {
		t.Fatalf("sweep: %v", err)
	}

	if len(removed) != 1 || removed[0] != orphan {
		t.Errorf("removed=%v, want only %s", removed, orphan)
	}
	if got := readFile(t, former+"/SKILL.md"); got != "mine\n" {
		t.Errorf("directory content changed: %q", got)
	}
}

func TestRecordLedgerWrites_CollectsSumsForWrittenPaths(t *testing.T) {
	writes := []adapters.WrittenFile{
		{Path: "ref.md", Action: "create", Sum: "abc"},
		{Path: "SKILL.md", Action: "skip"},
		{Path: "gone.md", Action: "delete", Sum: "zzz"},
	}
	var session []string
	sums := map[string]string{}
	recordLedgerWrites(writes, &session, sums)

	if got, ok := sums["ref.md"]; !ok || got != "abc" {
		t.Errorf("sums[ref.md]=%q,%v, want abc", got, ok)
	}
	if got, ok := sums["SKILL.md"]; !ok || got != "" {
		t.Errorf("header file must be recorded as written with no sum, got %q,%v", got, ok)
	}
	if _, ok := sums["gone.md"]; ok {
		t.Error("deleted path must not be recorded")
	}
}


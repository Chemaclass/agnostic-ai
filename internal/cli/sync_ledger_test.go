func TestSweepLedgerOrphans_KeepsParentWhenSiblingsRemain(t *testing.T) {
	dir := t.TempDir()
	chdir(t, dir)

	orphan := filepath.Join(".x", "gone.toml")
	keeper := filepath.Join(".x", "stay.toml")
	if err := os.MkdirAll(filepath.Dir(orphan), 0o755); err != nil {
		t.Fatal(err)
	}
	body := "# Generated by agnostic-ai\nkey = 1\n"
	if err := os.WriteFile(orphan, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(keeper, []byte("# user\nkey = 2\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	removed, err := sweepLedgerOrphans(adapters.NewSession(), []string{orphan}, nil, false)
	if err != nil {
		t.Fatalf("sweep: %v", err)
	}
	if len(removed) != 1 {
		t.Errorf("removed=%v", removed)
	}
	if _, err := os.Stat(".x"); err != nil {
		t.Errorf("parent dir must stay because sibling remains: %v", err)
	}
}

func TestCoversAllConfiguredTargets(t *testing.T) {
	cases := []struct {
		name       string
		emitted    []string
		configured []string
		want       bool
	}{
		{"full run", []string{"claude", "codex"}, []string{"claude", "codex"}, true},
		{"order-independent", []string{"codex", "claude"}, []string{"claude", "codex"}, true},
		{"only subset", []string{"claude"}, []string{"claude", "codex"}, false},
		{"empty configured", []string{"claude"}, nil, true},
		{"superset still covers", []string{"claude", "codex", "cursor"}, []string{"claude", "codex"}, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := coversAllConfiguredTargets(tc.emitted, tc.configured); got != tc.want {
				t.Errorf("coversAllConfiguredTargets(%v, %v)=%v, want %v", tc.emitted, tc.configured, got, tc.want)
			}
		})
	}
}


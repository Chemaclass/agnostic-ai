func TestReconcilePartialLedger_PartialRunPreservesPriorOutputs(t *testing.T) {
	// --only claude: ledger holds only claude's files; codex's AGENTS.md
	// lives in prior. The merge keeps it so the sweep cannot delete it.
	ledger := []string{".claude/CLAUDE.md"}
	prior := []string{".claude/CLAUDE.md", "AGENTS.md"}
	got := reconcilePartialLedger(ledger, prior, false)
	want := map[string]bool{".claude/CLAUDE.md": true, "AGENTS.md": true}
	if len(got) != len(want) {
		t.Fatalf("got %v, want keys %v", got, want)
	}
	for _, p := range got {
		if !want[p] {
			t.Errorf("unexpected path %q in merged ledger", p)
		}
	}
}

// TestSweepLedgerOrphans_PartialRunDoesNotDeleteOtherTargets is the
// end-to-end guard for the --only data-loss bug: an un-synced target's
// file must survive when its path is folded back into the current set.
func TestSweepLedgerOrphans_PartialRunDoesNotDeleteOtherTargets(t *testing.T) {
	dir := t.TempDir()
	chdir(t, dir)

	other := "AGENTS.md" // owned by codex, not emitted this run
	body := "# Generated by agnostic-ai\nbody\n"
	if err := os.WriteFile(other, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}

	prior := []string{".claude/CLAUDE.md", other}
	ledger := reconcilePartialLedger([]string{".claude/CLAUDE.md"}, prior, false)
	removed, err := sweepLedgerOrphans(adapters.NewSession(), prior, ledger, false)
	if err != nil {
		t.Fatalf("sweep: %v", err)
	}
	if len(removed) != 0 {
		t.Errorf("partial run must not remove other target files, got %v", removed)
	}
	if _, err := os.Stat(other); err != nil {
		t.Errorf("other target's file was deleted: %v", err)
	}
}

// chdir is a local helper because the cli package does not already
// import testutil. Switching cwd lets sweepLedgerOrphans resolve the
// relative paths from the temp dir without picking up the host repo.
func chdir(t *testing.T, dir string) {
	t.Helper()
	prev, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chdir(prev) })
}

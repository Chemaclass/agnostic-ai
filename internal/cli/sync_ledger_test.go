func TestRecordLedgerWrites_KeepsCreatesUpdatesAndSkips(t *testing.T) {
	writes := []adapters.WrittenFile{
		{Path: "a.md", Action: "create"},
		{Path: "b.md", Action: "update"},
		{Path: "c.md", Action: "skip"},
		{Path: "d.md", Action: "delete"},
	}
	var session []string
	recordLedgerWrites(writes, &session)
	want := []string{"a.md", "b.md", "c.md"}
	if len(session) != len(want) {
		t.Fatalf("session=%v, want %v", session, want)
	}
	for i, p := range want {
		if session[i] != p {
			t.Errorf("session[%d]=%q, want %q", i, session[i], p)
		}
	}
}


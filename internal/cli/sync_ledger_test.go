func TestSweepLedgerOrphans_RemovesProvenanceFilesNotInCurrent(t *testing.T) {
	dir := t.TempDir()
	chdir(t, dir)

	orphan := filepath.Join(".legacy", "old.toml")
	if err := os.MkdirAll(filepath.Dir(orphan), 0o755); err != nil {
		t.Fatal(err)
	}
	body := "# Generated by agnostic-ai\nkey = 1\n"
	if err := os.WriteFile(orphan, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}

	removed, _, err := sweepLedgerOrphans(adapters.NewSession(), []string{orphan}, nil, []string{"active/new.toml"})
	if err != nil {
		t.Fatalf("sweep: %v", err)
	}
	if len(removed) != 1 || removed[0] != orphan {
		t.Errorf("removed=%v, want [%q]", removed, orphan)
	}
	if _, err := os.Stat(orphan); !os.IsNotExist(err) {
		t.Errorf("orphan still on disk: %v", err)
	}
	if _, err := os.Stat(".legacy"); !os.IsNotExist(err) {
		t.Errorf("empty parent dir should have been pruned: %v", err)
	}
}


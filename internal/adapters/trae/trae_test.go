// TestEmit_CommandDescriptionFallsBackToName mirrors SkillMarkdown's
// convention: a command with no description still gets a non-empty one
// so the required frontmatter key is never written empty.
func TestEmit_CommandDescriptionFallsBackToName(t *testing.T) {
	dir := t.TempDir()
	testutil.Chdir(t, dir)

	entries := []spec.Entry{{Kind: spec.KindCommand, Name: "deploy", Body: "Run the deploy steps."}}
	if err := New().Emit(emit.NewSession(), spec.NewBundle(entries), &config.Config{}, false); err != nil {
		t.Fatal(err)
	}
	got := readFile(t, filepath.Join(dir, ".trae/commands/deploy.md"))
	if !strings.Contains(got, "description: deploy") {
		t.Errorf("expected description to fall back to the command name:\n%s", got)
	}
}

// TestEmit_CommandFrontmatterOmitsUnconfirmedKeys locks the evidence
// this adapter is built on: only `name` and `description` are confirmed
// native to a Trae command file (239 real .trae/commands/*.md files via
// GitHub code search, cross-tool-generated files excluded). A spec that
// sets tools/model/argument-hint (Claude Code's own command vocabulary)
// must not leak them into the Trae file.
func TestEmit_CommandFrontmatterOmitsUnconfirmedKeys(t *testing.T) {
	dir := t.TempDir()
	testutil.Chdir(t, dir)

	entries := []spec.Entry{
		{
			Kind: spec.KindCommand,
			Name: "deploy",
			Meta: map[string]any{
				"description":   "Ship it",
				"tools":         []any{"Bash"},
				"model":         "opus",
				"argument-hint": "[env]",
			},
			Body: "Run the deploy steps.",
		},
	}
	if err := New().Emit(emit.NewSession(), spec.NewBundle(entries), &config.Config{}, false); err != nil {
		t.Fatal(err)
	}
	got := readFile(t, filepath.Join(dir, ".trae/commands/deploy.md"))
	for _, leaked := range []string{"tools:", "model:", "argument-hint:"} {
		if strings.Contains(got, leaked) {
			t.Errorf("unexpected leaked frontmatter %q in %s", leaked, got)
		}
	}
}

// TestEmit_CommandXTraeKeyReachesFrontmatter confirms the standard
// x-<target> escape hatch still works for commands: an author-declared
// custom key is an explicit per-spec opt-in, not a key inferred from the
// vendor's default format, so it is not covered by the "only name and
// description" evidence restriction. See #367.
func TestEmit_CommandXTraeKeyReachesFrontmatter(t *testing.T) {
	dir := t.TempDir()
	testutil.Chdir(t, dir)

	entries := []spec.Entry{
		{
			Kind: spec.KindCommand,
			Name: "deploy",
			Meta: map[string]any{
				"description": "Ship it",
				"x-trae":      map[string]any{"some-trae-key": "value"},
			},
			Body: "Run the deploy steps.",
		},
	}
	if err := New().Emit(emit.NewSession(), spec.NewBundle(entries), &config.Config{}, false); err != nil {
		t.Fatal(err)
	}
	got := readFile(t, filepath.Join(dir, ".trae/commands/deploy.md"))
	if !strings.Contains(got, "some-trae-key: value") {
		t.Errorf("expected x-trae custom key to reach frontmatter:\n%s", got)
	}
	if strings.Contains(got, "x-trae:") {
		t.Errorf("x-trae wrapper key itself must not leak:\n%s", got)
	}
}


func TestEmit_WritesRulesAgentsAndSkills(t *testing.T) {
	dir := t.TempDir()
	testutil.Chdir(t, dir)

	entries := []spec.Entry{
		{Kind: spec.KindRule, Name: "r1", Body: "rule"},
		{Kind: spec.KindAgent, Name: "ag1", Body: "agent"},
		{Kind: spec.KindSkill, Name: "sk1", Path: "skills/sk1/SKILL.md", Body: "skill"},
	}
	if err := New().Emit(emit.NewSession(), spec.NewBundle(entries), &config.Config{}, false); err != nil {
		t.Fatal(err)
	}

	cases := map[string]string{
		".trae/rules/r1.md":         "rule",
		".trae/rules/agent-ag1.md":  "agent",
		".trae/skills/sk1/SKILL.md": "skill",
	}
	for p, want := range cases {
		got, err := os.ReadFile(filepath.Join(dir, p))
		if err != nil {
			t.Fatalf("missing %s: %v", p, err)
		}
		body := string(got)
		if !strings.Contains(body, "Generated by agnostic-ai") {
			t.Errorf("%s missing provenance header:\n%s", p, body)
		}
		if !strings.Contains(body, want) {
			t.Errorf("%s missing body %q:\n%s", p, want, body)
		}
	}

	// The pre-fix flat form must not be written; Trae only loads
	// SKILL.md from a folder (docs.trae.ai/ide/skills), so a skill
	// shipping sibling assets would lose them silently to a rule-form
	// file that was never a skill.
	if _, err := os.Stat(filepath.Join(dir, ".trae/rules/skill-sk1.md")); !os.IsNotExist(err) {
		t.Errorf("expected no flat .trae/rules/skill-sk1.md, err=%v", err)
	}
}


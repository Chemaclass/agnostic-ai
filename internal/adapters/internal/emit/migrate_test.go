// TestMigrateLegacyPath_CrossesDirectories pins #1114's motivating case:
// a legacy path in one directory and a new default in another, which
// legacyFilePath's same-directory join cannot express.
func TestMigrateLegacyPath_CrossesDirectories(t *testing.T) {
	sess := NewSession()
	dir := testutil.TempCwd(t)
	if err := os.MkdirAll(filepath.Join(dir, ".agent"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, ".agent", "AGENTS.md"),
		[]byte("Generated by agnostic-ai\nstale\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := sess.MigrateLegacyPath("antigravity", ".agent/AGENTS.md", ".agents/AGENTS.md", false); err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(filepath.Join(dir, ".agent", "AGENTS.md")); !os.IsNotExist(err) {
		t.Errorf("legacy should be renamed, err=%v", err)
	}
	got := readFileString(t, filepath.Join(dir, ".agent", "AGENTS.md.bak"))
	if !strings.Contains(got, "stale") {
		t.Errorf("backup should preserve old content: %q", got)
	}
}

// An existing `.bak` is never clobbered: `os.Rename` would silently
// overwrite it on Unix, discarding whatever an earlier migration (or a
// hand-made copy) left there. Leaving the legacy file in place instead
// was itself a data-loss bug: a legacy path already recorded in an
// older, already-persisted sync ledger reads as an orphan to the next
// sync's sweep once this run stops declaring it a managed output, and
// the sweep deletes it on the strength of its own provenance marker,
// discarding bytes that were never backed up anywhere (#1114 review).
// The fix numbers past the taken name instead: both the earlier backup
// and the current legacy content end up on disk, and the legacy path
// itself is always removed.
func TestMigrateLegacyPath_PreservesExistingBackup(t *testing.T) {
	sess := NewSession()
	dir := testutil.TempCwd(t)
	if err := os.WriteFile(filepath.Join(dir, "LEGACY.md"),
		[]byte("Generated by agnostic-ai\nnew stale content\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "LEGACY.md.bak"),
		[]byte("earlier backup, must survive\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	var warner bytes.Buffer
	prev := Warner
	Warner = &warner
	t.Cleanup(func() { Warner = prev })

	if err := sess.MigrateLegacyPath("amp", "LEGACY.md", "NEW.md", false); err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(filepath.Join(dir, "LEGACY.md")); !os.IsNotExist(err) {
		t.Errorf("legacy file should be removed once its bytes are backed up, err=%v", err)
	}
	if got := readFileString(t, filepath.Join(dir, "LEGACY.md.bak")); got != "earlier backup, must survive\n" {
		t.Errorf("existing backup must not be overwritten, got: %q", got)
	}
	if got := readFileString(t, filepath.Join(dir, "LEGACY.md.bak.1")); !strings.Contains(got, "new stale content") {
		t.Errorf("current legacy content should land in a numbered backup, got: %q", got)
	}
	if !strings.Contains(warner.String(), "LEGACY.md.bak.1") {
		t.Errorf("expected a warning naming the numbered backup, got %q", warner.String())
	}
}

// Numbering keeps going past more than one taken name.
func TestMigrateLegacyPath_NumbersPastSeveralTakenBackups(t *testing.T) {
	sess := NewSession()
	dir := testutil.TempCwd(t)
	if err := os.WriteFile(filepath.Join(dir, "LEGACY.md"),
		[]byte("Generated by agnostic-ai\nthird generation\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"LEGACY.md.bak", "LEGACY.md.bak.1"} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte("taken\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	if err := sess.MigrateLegacyPath("amp", "LEGACY.md", "NEW.md", false); err != nil {
		t.Fatal(err)
	}

	if got := readFileString(t, filepath.Join(dir, "LEGACY.md.bak.2")); !strings.Contains(got, "third generation") {
		t.Errorf("expected the next free numbered backup, got: %q", got)
	}
	for _, name := range []string{"LEGACY.md.bak", "LEGACY.md.bak.1"} {
		if got := readFileString(t, filepath.Join(dir, name)); got != "taken\n" {
			t.Errorf("existing numbered backup %s must not be overwritten, got: %q", name, got)
		}
	}
}

// A rollback in the same transaction restores the legacy file and
// removes the backup this move created, so a sync pass that fails
// after the migration leaves the working tree exactly as it found it.
func TestMigrateLegacyPath_RollbackRestoresLegacyFile(t *testing.T) {
	sess := NewSession()
	dir := testutil.TempCwd(t)
	const original = "Generated by agnostic-ai\noriginal content\n"
	if err := os.WriteFile(filepath.Join(dir, "LEGACY.md"), []byte(original), 0o644); err != nil {
		t.Fatal(err)
	}

	sess.StartTransaction()
	if err := sess.MigrateLegacyPath("amp", "LEGACY.md", "NEW.md", false); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, "LEGACY.md.bak")); err != nil {
		t.Fatalf("expected backup before rollback: %v", err)
	}

	if err := sess.Rollback(); err != nil {
		t.Fatal(err)
	}

	if got := readFileString(t, filepath.Join(dir, "LEGACY.md")); got != original {
		t.Errorf("rollback should restore the legacy file verbatim, got: %q", got)
	}
	if _, err := os.Stat(filepath.Join(dir, "LEGACY.md.bak")); !os.IsNotExist(err) {
		t.Errorf("rollback should remove the backup this move created, err=%v", err)
	}
}

// sync.unmanaged matching the conventional backup destination (not the
// legacy path itself) skips that one candidate name, not the whole
// migration: the numbering search moves on to the next free name
// instead of writing over a user-owned path.
func TestMigrateLegacyPath_SkipsUnmanagedBackupCandidate(t *testing.T) {
	sess := NewSession()
	dir := testutil.TempCwd(t)
	body := "Generated by agnostic-ai\nstale\n"
	if err := os.WriteFile(filepath.Join(dir, "LEGACY.md"), []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	sess.SetUnmanaged([]string{"LEGACY.md.bak"})

	if err := sess.MigrateLegacyPath("amp", "LEGACY.md", "NEW.md", false); err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(filepath.Join(dir, "LEGACY.md")); !os.IsNotExist(err) {
		t.Errorf("legacy file should be removed once its bytes are backed up, err=%v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "LEGACY.md.bak")); !os.IsNotExist(err) {
		t.Errorf("no backup should be written over an unmanaged path, err=%v", err)
	}
	if got := readFileString(t, filepath.Join(dir, "LEGACY.md.bak.1")); got != body {
		t.Errorf("expected the backup at the next non-unmanaged name, got: %q", got)
	}
}

// TestMergeJSONFile_KeepsUserKeysInJSONC regresses #725. kilo, qoder and
// augment each merge into a file their vendor documents as JSONC, and
// `encoding/json` rejects both `//` comments and trailing commas. The
// parse error was swallowed and readExistingJSON returned an empty
// document, so the write back dropped every user-authored key,
// credentials and permission settings included.
func TestMergeJSONFile_KeepsUserKeysInJSONC(t *testing.T) {
	sess := NewSession()
	dir := testutil.TempCwd(t)
	path := filepath.Join(dir, "settings.json")
	const existing = `{
  // Provider credentials, hand-authored.
  "provider": {
    "name": "anthropic",
    "apiKey": "sk-secret-value",
  },
  /* block form too */
  "endpoint": "https://example.com//v1",
  "experimental": { "autoApprove": false },
}
`
	if err := os.WriteFile(path, []byte(existing), 0o644); err != nil {
		t.Fatal(err)
	}

	err := sess.MergeJSONFile(path, map[string]any{"mcp": map[string]any{"linear": map[string]any{}}}, false)
	if err != nil {
		t.Fatal(err)
	}

	got := readFileString(t, path)
	for _, want := range []string{
		`"provider"`, `"sk-secret-value"`, `"experimental"`, `"mcp"`,
		`"https://example.com//v1"`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("merged file lost %s:\n%s", want, got)
		}
	}
}

// TestMergeJSONFile_FailsLoudlyOnUnparseableFile pins the other half of
// #725: a non-empty file that is neither JSON nor JSONC aborts the write
// instead of being silently replaced by the managed keys alone.
func TestMergeJSONFile_FailsLoudlyOnUnparseableFile(t *testing.T) {
	sess := NewSession()
	dir := testutil.TempCwd(t)
	path := filepath.Join(dir, "settings.json")
	const existing = "{ this is not json at all"
	if err := os.WriteFile(path, []byte(existing), 0o644); err != nil {
		t.Fatal(err)
	}

	err := sess.MergeJSONFile(path, map[string]any{"mcp": map[string]any{}}, false)
	if err == nil {
		t.Fatal("expected an error on an unparseable existing file")
	}
	if !strings.Contains(err.Error(), "settings.json") {
		t.Errorf("error should name the file: %v", err)
	}
	if got := readFileString(t, path); got != existing {
		t.Errorf("unparseable file must stay untouched, got:\n%s", got)
	}
}


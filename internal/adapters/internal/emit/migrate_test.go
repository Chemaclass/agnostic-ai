// TestMergeJSONFile_CaptureReadsExistingUserKeys regresses #465. Capture
// mode (used by `sync --check`, `doctor`, and `status`) must read the
// existing file so the captured bytes carry the user's sibling keys, not
// the managed keys alone. Otherwise drift is reported falsely and
// `doctor --fix` writes the managed-only capture back, deleting the
// user's keys.
func TestMergeJSONFile_CaptureReadsExistingUserKeys(t *testing.T) {
	sess := NewSession()
	dir := testutil.TempCwd(t)
	path := filepath.Join(dir, "opencode.json")
	const existing = `{"theme": "dark"}`
	if err := os.WriteFile(path, []byte(existing), 0o644); err != nil {
		t.Fatal(err)
	}

	sess.StartCapture()
	err := sess.MergeJSONFile(path, map[string]any{"mcp": map[string]any{"fs": map[string]any{}}}, false)
	files := sess.StopCapture()
	if err != nil {
		t.Fatal(err)
	}

	if len(files) != 1 {
		t.Fatalf("want 1 captured file, got %d", len(files))
	}
	for _, want := range []string{`"theme"`, `"dark"`, `"mcp"`} {
		if !strings.Contains(files[0].Content, want) {
			t.Errorf("captured content missing %q:\n%s", want, files[0].Content)
		}
	}

	// Capture must not write through to disk.
	disk, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(disk) != existing {
		t.Errorf("capture mutated disk: %s", disk)
	}
}

func TestMergeJSONFileNested_PreservesNativeObjectSiblings(t *testing.T) {
	dir := testutil.TempCwd(t)
	path := filepath.Join(dir, "settings.json")
	if err := os.WriteFile(path, []byte(`{"model":{"name":"old","temperature":0.2},"theme":"dark"}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := NewSession().MergeJSONFileNested(path, map[string]any{
		"model": map[string]any{"name": "new"},
	}, []string{"model"}, false); err != nil {
		t.Fatal(err)
	}
	var got map[string]any
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(data, &got); err != nil {
		t.Fatal(err)
	}
	model := got["model"].(map[string]any)
	if model["name"] != "new" || model["temperature"] != 0.2 || got["theme"] != "dark" {
		t.Errorf("nested merge lost native settings: %#v", got)
	}
}

func TestMigrateLegacyFile_RenamesWhenAgnosticGenerated(t *testing.T) {
	sess := NewSession()
	dir := testutil.TempCwd(t)
	if err := os.WriteFile(filepath.Join(dir, "LEGACY.md"),
		[]byte("Generated by agnostic-ai\nstale\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	var warner bytes.Buffer
	prev := Warner
	Warner = &warner
	t.Cleanup(func() { Warner = prev })

	sess.MigrateLegacyFile(&config.Config{}, "amp", "LEGACY.md", "NEW.md", false)

	if _, err := os.Stat(filepath.Join(dir, "LEGACY.md")); !os.IsNotExist(err) {
		t.Errorf("legacy should be renamed, err=%v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "LEGACY.md.bak")); err != nil {
		t.Errorf("backup should exist: %v", err)
	}
	got := warner.String()
	for _, want := range []string{"amp:", "LEGACY.md", "NEW.md"} {
		if !bytes.Contains([]byte(got), []byte(want)) {
			t.Errorf("warner missing %q: %q", want, got)
		}
	}
}


func writeTestFile(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestRemoveOwned_RemovesHeaderlessFileWhoseBytesMatchSum(t *testing.T) {
	path := filepath.Join(t.TempDir(), "references", "a.md")
	body := "ref\n"
	writeTestFile(t, path, body)

	removed, err := NewSession().RemoveOwned(path, ContentSum(body), false)
	if err != nil {
		t.Fatalf("RemoveOwned: %v", err)
	}
	if !removed {
		t.Error("removed = false, want true")
	}
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Errorf("file still on disk: %v", err)
	}
}


// Claude Code loads a nested CLAUDE.md that imports its AGENTS.md; with
// the scoped rule in .claude/rules it would load the same text twice.
func TestCheckScopedDestination_AllowsCompanionClaudeReplaces(t *testing.T) {
	testutil.Chdir(t, t.TempDir())
	writeScoped(t, "services/api/AGENTS.md", "Use integer minor units.\n")
	writeScoped(t, "services/api/CLAUDE.md", "@AGENTS.md\n")

	replaced := map[string]bool{"services/api/CLAUDE.md": true}
	if err := CheckScopedDestination("services/api/AGENTS.md", scopedRender, replaced); err != nil {
		t.Fatalf("CheckScopedDestination() = %v, want the companion allowed", err)
	}
}

// A companion the Claude adapter keeps would load the scoped AGENTS.md
// next to any other copy, so it still blocks sync.
func TestCheckScopedDestination_RejectsCompanionClaudeKeeps(t *testing.T) {
	testutil.Chdir(t, t.TempDir())
	writeScoped(t, "services/api/CLAUDE.md", "@AGENTS.md\n")

	if err := CheckScopedDestination("services/api/AGENTS.md", scopedRender, nil); err == nil {
		t.Fatal("CheckScopedDestination() = nil, want the companion rejected")
	}
}

func TestAgentsCompanionDirs(t *testing.T) {
	rule := func(name, scope string) spec.Entry {
		return spec.Entry{Kind: spec.KindRule, Name: name, Scope: scope}
	}
	rules := []spec.Entry{rule("root", ""), rule("api", "services/api"), rule("money", "services/api"), rule("web", "apps/web")}
	cases := []struct {
		name string
		cfg  config.Config
		want []string
	}{
		{"rules dir", config.Config{}, []string{"services/api", "apps/web"}},
		{"rules file", config.Config{Outputs: map[string]config.Output{"claude": {RulesFile: "CLAUDE.md"}}}, nil},
		{"unmanaged companion", config.Config{Sync: config.SyncConfig{Unmanaged: []string{"apps/web/CLAUDE.md"}}}, []string{"services/api"}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := AgentsCompanionDirs(&c.cfg, rules)
			if len(got) != len(c.want) {
				t.Fatalf("AgentsCompanionDirs() = %v, want %v", got, c.want)
			}
			for i := range got {
				if got[i] != c.want[i] {
					t.Errorf("AgentsCompanionDirs() = %v, want %v", got, c.want)
				}
			}
		})
	}
}

func TestRemoveAgentsCompanion(t *testing.T) {
	const generated = "<!-- Generated by agnostic-ai. Do not edit this file directly. -->\n\nUse integer minor units.\n"
	cases := []struct {
		name, agents, claude, covered string
		dryRun                        bool
		before                        func(*Session)
		after                         func(*testing.T, *Session)
		wantKept, wantBackup          bool
	}{
		{name: "companion the rules cover", agents: "# API\n\nUse integer minor units.\n", claude: "@AGENTS.md\n", covered: "Use integer minor units.\n"},
		{name: "companion of a generated AGENTS.md", agents: generated, claude: "@AGENTS.md\n"},
		{name: "companion of uncovered text", agents: "Use integer minor units.\n\nDeploy on Fridays.\n", claude: "@AGENTS.md\n", covered: "Use integer minor units.\n", wantKept: true},
		{name: "CLAUDE.md with its own text", agents: generated, claude: "@AGENTS.md\n\nRun the API tests.\n", wantKept: true},
		{name: "dry run", agents: generated, claude: "@AGENTS.md\n", dryRun: true, wantKept: true},
		{
			name: "capture", agents: generated, claude: "@AGENTS.md\n", wantKept: true,
			before: func(s *Session) { s.StartCapture() },
			after: func(t *testing.T, s *Session) {
				s.StopCapture()
				if got := s.CapturedRemovals(); len(got) != 1 || got[0].Path != filepath.FromSlash("services/api/CLAUDE.md") {
					t.Errorf("CapturedRemovals() = %v, want the companion", got)
				}
			},
		},
		{
			name: "rollback", agents: generated, claude: "@AGENTS.md\n", wantKept: true,
			before: func(s *Session) { s.StartTransaction() },
			after: func(t *testing.T, s *Session) {
				if err := s.Rollback(); err != nil {
					t.Fatal(err)
				}
			},
		},
		{
			name: "backup", agents: generated, claude: "@AGENTS.md\n", wantBackup: true,
			before: func(s *Session) { s.SetBackup(true) },
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			testutil.Chdir(t, t.TempDir())
			writeScoped(t, "services/api/AGENTS.md", c.agents)
			writeScoped(t, "services/api/CLAUDE.md", c.claude)
			sess := NewSession()
			if c.before != nil {
				c.before(sess)
			}

			if err := sess.RemoveAgentsCompanion("services/api", c.covered, c.dryRun); err != nil {
				t.Fatal(err)
			}
			if c.after != nil {
				c.after(t, sess)
			}

			data, err := os.ReadFile("services/api/CLAUDE.md")
			switch {
			case c.wantKept && (err != nil || string(data) != c.claude):
				t.Errorf("CLAUDE.md = %q, %v, want it kept as %q", data, err, c.claude)
			case !c.wantKept && !os.IsNotExist(err):
				t.Errorf("CLAUDE.md should be removed, stat err = %v", err)
			}
			backup, err := os.ReadFile("services/api/CLAUDE.md.bak")
			switch {
			case c.wantBackup && (err != nil || string(backup) != c.claude):
				t.Errorf("CLAUDE.md.bak = %q, %v, want %q", backup, err, c.claude)
			case !c.wantBackup && !os.IsNotExist(err):
				t.Errorf("CLAUDE.md.bak should not exist, stat err = %v", err)
			}
		})
	}
}

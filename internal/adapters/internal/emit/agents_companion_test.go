func TestIsAgentsCompanion(t *testing.T) {
	cases := []struct {
		name, text string
		want       bool
	}{
		{"import only", "@AGENTS.md\n", true},
		{"titled import", "# CLAUDE.md\n\n@./AGENTS.md\n", true},
		{"title in lower case", "# claude.md\n\n@AGENTS.md\n", true},
		{"own instructions", "# CLAUDE.md\n\n@AGENTS.md\n\nUse the Dashboard.\n", false},
		{"instruction as a heading", "@AGENTS.md\n\n# Never run migrations against prod\n", false},
		{"meaningful title", "# Never run migrations against prod\n\n@AGENTS.md\n", false},
		{"section heading", "# CLAUDE.md\n\n@AGENTS.md\n\n## Deploys\n", false},
		{"import in a code fence", "```\n@AGENTS.md\n```\n", false},
		{"generated file", "<!-- Generated by agnostic-ai. Do not edit this file directly. -->\n\n@AGENTS.md\n", false},
		{"no import", "# Notes\n", false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := IsAgentsCompanion(c.text); got != c.want {
				t.Errorf("IsAgentsCompanion(%q) = %v, want %v", c.text, got, c.want)
			}
		})
	}
}


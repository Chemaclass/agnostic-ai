func TestIsAgentsCompanion(t *testing.T) {
	cases := []struct {
		name, text string
		want       bool
	}{
		{"import only", "@AGENTS.md\n", true},
		{"titled import", "# CLAUDE.md\n\n@./AGENTS.md\n", true},
		{"own instructions", "# CLAUDE.md\n\n@AGENTS.md\n\nUse the Dashboard.\n", false},
		{"import in a code fence", "```\n@AGENTS.md\n```\n", false},
		{"generated file", "<!-- Generated by agnostic-ai. Do not edit this file directly. -->\n\n@AGENTS.md\n", false},
		{"no import", "# Notes\n", false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := IsAgentsCompanion(c.text); got != c.want {
				t.Errorf("IsAgentsCompanion(%q) = %v, want %v", c.text, got, c.want)
			}
		})
	}
}

func TestSplitAgentsCompanion_KeepsTextOnlyClaudeReads(t *testing.T) {
	rest, ok := SplitAgentsCompanion("# CLAUDE.md\n\n@AGENTS.md\n\n## Claude Code specifics\n\n- Use the Dashboard.\n")
	if !ok {
		t.Fatal("SplitAgentsCompanion() ok = false, want the AGENTS.md import found")
	}
	if want := "## Claude Code specifics\n\n- Use the Dashboard."; rest != want {
		t.Errorf("rest = %q, want %q", rest, want)
	}
}

// Claude Code loads a nested CLAUDE.md that imports its AGENTS.md; with
// the scoped rule in .claude/rules it would load the same text twice.
func TestCheckScopedDestination_AllowsClaudeCompanion(t *testing.T) {
	testutil.Chdir(t, t.TempDir())
	writeScoped(t, "services/api/AGENTS.md", "Use integer minor units.\n")
	writeScoped(t, "services/api/CLAUDE.md", "@AGENTS.md\n")

	if err := CheckScopedDestination("services/api/AGENTS.md", scopedRender); err != nil {
		t.Fatalf("CheckScopedDestination() = %v, want the companion allowed", err)
	}
}

func TestRemoveAgentsCompanion_RemovesCompanionTheRulesCover(t *testing.T) {
	testutil.Chdir(t, t.TempDir())
	writeScoped(t, "services/api/AGENTS.md", "# API\n\nUse integer minor units.\n")
	writeScoped(t, "services/api/CLAUDE.md", "@AGENTS.md\n")

	if err := NewSession().RemoveAgentsCompanion("services/api", "Use integer minor units.\n", false); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat("services/api/CLAUDE.md"); !os.IsNotExist(err) {
		t.Errorf("companion should be removed, stat err = %v", err)
	}
}


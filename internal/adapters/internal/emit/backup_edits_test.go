// A rolled-back sync removes the backup it made, so a retry does not take
// it for an earlier one and leave the edit stuck in place.
func TestRollback_RemovesAHandEditBackupTheRunMade(t *testing.T) {
	path := filepath.Join(t.TempDir(), "SKILL.md")
	if err := os.WriteFile(path, []byte("hand edit\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	s := NewSession()
	s.BackUpEditsSince(map[string]string{path: ContentSum("generated\n")})
	s.StartTransaction()
	if err := s.WriteFile(path, "generated twice\n", false); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(path + ".bak"); err != nil {
		t.Fatalf("no backup before rollback: %v", err)
	}

	if err := s.Rollback(); err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(path + ".bak"); !os.IsNotExist(err) {
		t.Errorf("rollback kept the backup: %v", err)
	}
	if data, _ := os.ReadFile(path); string(data) != "hand edit\n" {
		t.Errorf("rollback left %q, want the hand edit", data)
	}
}

// A link's target may live outside the project, so sync never copies it
// into a backup.
func TestBackUpEdits_NeverCopiesALinkTarget(t *testing.T) {
	dir := t.TempDir()
	outside := filepath.Join(t.TempDir(), "secret.txt")
	if err := os.WriteFile(outside, []byte("secret\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "SKILL.md")
	if err := os.Symlink(outside, path); err != nil {
		t.Skip(err)
	}
	s := NewSession()
	s.BackUpEditsSince(map[string]string{path: ContentSum("generated\n")})

	_ = s.WriteFile(path, "generated twice\n", false)

	if _, err := os.Lstat(path + ".bak"); err == nil {
		t.Error("sync copied a link target into a backup")
	}
}

func TestRemoveGenerated_ProtectsEditsAcrossModes(t *testing.T) {
	for _, mode := range []string{"capture", "dry run", "rollback"} {
		t.Run(mode, func(t *testing.T) {
			testutil.Chdir(t, t.TempDir())
			const path = "config.toml"
			generated := "# Generated by agnostic-ai\nvalue = 1\n"
			edited := generated + "# edit\n"
			if err := os.WriteFile(path, []byte(edited), 0o600); err != nil {
				t.Fatal(err)
			}
			s := NewSession()
			s.BackUpEditsSince(map[string]string{path: ContentSum(generated)})
			switch mode {
			case "capture":
				s.StartCapture()
			case "rollback":
				s.StartTransaction()
			}
			if err := s.RemoveGenerated(path, mode == "dry run"); err != nil {
				t.Fatal(err)
			}
			if mode == "capture" && len(s.CapturedRemovals()) != 1 {
				t.Error("capture missed removal")
			}
			if mode == "rollback" {
				if _, err := os.Stat(path + ".bak"); err != nil {
					t.Fatalf("backup: %v", err)
				}
				if err := s.Rollback(); err != nil {
					t.Fatal(err)
				}
			}
			if got, err := os.ReadFile(path); err != nil || string(got) != edited {
				t.Errorf("file = %q, %v", got, err)
			}
			if _, err := os.Lstat(path + ".bak"); !os.IsNotExist(err) {
				t.Errorf("backup remains: %v", err)
			}
		})
	}
}

func TestRemoveGenerated_KeepsEditBehindSymlinkedDirectory(t *testing.T) {
	testutil.Chdir(t, t.TempDir())
	outside := t.TempDir()
	const path = "linked/config.toml"
	generated := "# Generated by agnostic-ai\nvalue = 1\n"
	edited := generated + "# edit\n"
	if err := os.WriteFile(filepath.Join(outside, "config.toml"), []byte(edited), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, "linked"); err != nil {
		t.Skip(err)
	}
	s := NewSession()
	s.BackUpEditsSince(map[string]string{path: ContentSum(generated)})
	s.StartDetailedRecording()
	if err := s.RemoveGenerated(path, false); err != nil {
		t.Fatal(err)
	}
	writes := s.StopDetailedRecording()
	if len(writes) != 1 || writes[0].Action != "edited" {
		t.Errorf("writes = %+v", writes)
	}
	if got, err := os.ReadFile(filepath.Join(outside, "config.toml")); err != nil || string(got) != edited {
		t.Errorf("file = %q, %v", got, err)
	}
	if _, err := os.Lstat(filepath.Join(outside, "config.toml.bak")); !os.IsNotExist(err) {
		t.Errorf("wrote backup through link: %v", err)
	}
}

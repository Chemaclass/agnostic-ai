// A rolled-back sync removes the backup it made, so a retry does not take
// it for an earlier one and leave the edit stuck in place.
func TestRollback_RemovesAHandEditBackupTheRunMade(t *testing.T) {
	path := filepath.Join(t.TempDir(), "SKILL.md")
	if err := os.WriteFile(path, []byte("hand edit\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	s := NewSession()
	s.BackUpEditsSince(map[string]string{path: ContentSum("generated\n")})
	s.StartTransaction()
	if err := s.WriteFile(path, "generated twice\n", false); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(path + ".bak"); err != nil {
		t.Fatalf("no backup before rollback: %v", err)
	}

	if err := s.Rollback(); err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(path + ".bak"); !os.IsNotExist(err) {
		t.Errorf("rollback kept the backup: %v", err)
	}
	if data, _ := os.ReadFile(path); string(data) != "hand edit\n" {
		t.Errorf("rollback left %q, want the hand edit", data)
	}
}

// A link's target may live outside the project, so sync never copies it
// into a backup.
func TestBackUpEdits_NeverCopiesALinkTarget(t *testing.T) {
	dir := t.TempDir()
	outside := filepath.Join(t.TempDir(), "secret.txt")
	if err := os.WriteFile(outside, []byte("secret\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "SKILL.md")
	if err := os.Symlink(outside, path); err != nil {
		t.Skip(err)
	}
	s := NewSession()
	s.BackUpEditsSince(map[string]string{path: ContentSum("generated\n")})

	_ = s.WriteFile(path, "generated twice\n", false)

	if _, err := os.Lstat(path + ".bak"); err == nil {
		t.Error("sync copied a link target into a backup")
	}
}

func TestRemoveGenerated_ProtectsEditsAcrossModes(t *testing.T) {
	for _, mode := range []string{"capture", "dry run", "rollback"} {
		t.Run(mode, func(t *testing.T) {
			testutil.Chdir(t, t.TempDir())
			const path = "config.toml"
			generated := "# Generated by agnostic-ai\nvalue = 1\n"
			edited := generated + "# edit\n"
			if err := os.WriteFile(path, []byte(edited), 0o600); err != nil {
				t.Fatal(err)
			}
			s := NewSession()
			s.BackUpEditsSince(map[string]string{path: ContentSum(generated)})
			switch mode {
			case "capture":
				s.StartCapture()
			case "rollback":
				s.StartTransaction()
			}
			if err := s.RemoveGenerated(path, mode == "dry run"); err != nil {
				t.Fatal(err)
			}
			if mode == "capture" && len(s.CapturedRemovals()) != 1 {
				t.Error("capture missed removal")
			}
			if mode == "rollback" {
				if _, err := os.Stat(path + ".bak"); err != nil {
					t.Fatalf("backup: %v", err)
				}
				if err := s.Rollback(); err != nil {
					t.Fatal(err)
				}
			}
			if got, err := os.ReadFile(path); err != nil || string(got) != edited {
				t.Errorf("file = %q, %v", got, err)
			}
			if _, err := os.Lstat(path + ".bak"); !os.IsNotExist(err) {
				t.Errorf("backup remains: %v", err)
			}
		})
	}
}

func TestRemoveGenerated_KeepsEditBehindSymlinkedDirectory(t *testing.T) {
	testutil.Chdir(t, t.TempDir())
	outside := t.TempDir()
	const path = "linked/config.toml"
	generated := "# Generated by agnostic-ai\nvalue = 1\n"
	edited := generated + "# edit\n"
	if err := os.WriteFile(filepath.Join(outside, "config.toml"), []byte(edited), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, "linked"); err != nil {
		t.Skip(err)
	}
	s := NewSession()
	s.BackUpEditsSince(map[string]string{path: ContentSum(generated)})
	s.StartDetailedRecording()
	if err := s.RemoveGenerated(path, false); err != nil {
		t.Fatal(err)
	}
	writes := s.StopDetailedRecording()
	if len(writes) != 1 || writes[0].Action != "edited" {
		t.Errorf("writes = %+v", writes)
	}
	if got, err := os.ReadFile(filepath.Join(outside, "config.toml")); err != nil || string(got) != edited {
		t.Errorf("file = %q, %v", got, err)
	}
	if _, err := os.Lstat(filepath.Join(outside, "config.toml.bak")); !os.IsNotExist(err) {
		t.Errorf("wrote backup through link: %v", err)
	}
}

func TestSymlinkedParent_AbsolutePathStopsAtRoot(t *testing.T) {
	root := filepath.VolumeName(t.TempDir()) + string(filepath.Separator)
	path := filepath.Join(root, "agnostic-ai-root-termination-test", "config.toml")
	result := make(chan bool, 1)
	go func() { result <- symlinkedParent(path) }()
	select {
	case got := <-result:
		if got {
			t.Error("unexpected symlink in root path")
		}
	case <-time.After(2 * time.Second):
		t.Fatal("parent traversal did not stop at the root")
	}
}

// An edit made through a link to a file inside the project is saved as
// `<path>.bak` before the write, as for a regular file (#3736).
func TestBackUpEdits_SavesAnEditMadeThroughALinkInsideTheProject(t *testing.T) {
	testutil.Chdir(t, t.TempDir())
	if err := os.MkdirAll("notes", 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join("notes", "SKILL.md"), []byte("hand edit\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(filepath.Join("notes", "SKILL.md"), "SKILL.md"); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	s := NewSession()
	s.SetProjectRoot(".")
	s.BackUpEditsSince(map[string]string{"SKILL.md": ContentSum("generated\n")})

	if err := s.WriteFile("SKILL.md", "generated twice\n", false); err != nil {
		t.Fatal(err)
	}

	if data, err := os.ReadFile("SKILL.md.bak"); err != nil || string(data) != "hand edit\n" {
		t.Errorf("SKILL.md.bak = %q, %v; want the hand edit", data, err)
	}
	if got := s.OverwroteEdits(); len(got) != 1 || got[0] != "SKILL.md" {
		t.Errorf("OverwroteEdits = %v, want [SKILL.md]", got)
	}
}

// An edit made through a link to a file outside the project stays in
// place, since sync never copies such a target in (#3736). A project
// path linking out is refused earlier, so this covers an absolute path.
func TestBackUpEdits_KeepsAnEditMadeThroughALinkOutsideTheProject(t *testing.T) {
	outside := filepath.Join(t.TempDir(), "SKILL.md")
	if err := os.WriteFile(outside, []byte("hand edit\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	testutil.Chdir(t, t.TempDir())
	path := filepath.Join(t.TempDir(), "SKILL.md")
	if err := os.Symlink(outside, path); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	s := NewSession()
	s.BackUpEditsSince(map[string]string{path: ContentSum("generated\n")})

	if err := s.WriteFile(path, "generated twice\n", false); err != nil {
		t.Fatal(err)
	}

	if data, _ := os.ReadFile(outside); string(data) != "hand edit\n" {
		t.Errorf("link target = %q, want the hand edit kept", data)
	}
	if _, err := os.Lstat(path + ".bak"); err == nil {
		t.Error("sync copied a link target from outside the project into a backup")
	}
	if got := s.KeptEdits(); len(got) != 1 || got[0] != path {
		t.Errorf("KeptEdits = %v, want [%s]", got, path)
	}
}

// An output linked to another output holds that output's generated
// bytes, which is no hand edit.
func TestBackUpEdits_LinkToAnotherUnchangedOutputIsNoEdit(t *testing.T) {
	testutil.Chdir(t, t.TempDir())
	if err := os.WriteFile("AGENTS.md", []byte("agents\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("AGENTS.md", "CLAUDE.md"); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	s := NewSession()
	s.SetProjectRoot(".")
	s.BackUpEditsSince(map[string]string{"AGENTS.md": ContentSum("agents\n"), "CLAUDE.md": ContentSum("claude\n")})

	if err := s.WriteFile("CLAUDE.md", "claude twice\n", false); err != nil {
		t.Fatal(err)
	}

	if _, err := os.Lstat("CLAUDE.md.bak"); err == nil {
		t.Error("sync backed up another output's generated bytes as a hand edit")
	}
	if got := s.OverwroteEdits(); len(got) != 0 {
		t.Errorf("OverwroteEdits = %v, want none", got)
	}
}

package grok

import (
	"os"
	"strings"
	"testing"

	"github.com/chemaclass/agnostic-ai/internal/adapters/internal/emit"
	"github.com/chemaclass/agnostic-ai/internal/testutil"
)

func TestEmit_NativeTextHasProvenance(t *testing.T) {
	testutil.TempCwd(t)
	if err := New().Emit(emit.NewSession(), kitSinkBundle(), visibleConfig(), false); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{".grok/rules/style.md", "backend/.grok/rules/database.md", ".grok/agents/reviewer.md", ".grok/skills/review/SKILL.md", ".grok/commands/check.md", ".grok/config.toml"} {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(data), "Generated by agnostic-ai") {
			t.Errorf("missing header: %s", path)
		}
	}
}

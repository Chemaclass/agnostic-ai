// outputs.cline.hooks-dir redirects the scripts to the other directory
// resolveHooksConfigSearchPaths returns.
func TestEmit_Hook_HooksDirOverride(t *testing.T) {
	dir := testutil.TempCwd(t)

	cfg := &config.Config{
		Outputs: map[string]config.Output{"cline": {HooksDir: ".clinerules/hooks"}},
	}
	entries := []spec.Entry{
		{Kind: spec.KindHook, Name: "h", Meta: map[string]any{"event": "PostToolUse", "command": "echo hi"}},
	}
	if err := New().Emit(emit.NewSession(), spec.NewBundle(entries), cfg, false); err != nil {
		t.Fatalf("emit: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, ".clinerules/hooks/PostToolUse.sh")); err != nil {
		t.Errorf("expected .clinerules/hooks/PostToolUse.sh: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, ".cline/hooks/PostToolUse.sh")); !os.IsNotExist(err) {
		t.Errorf("expected no script at the default dir; err=%v", err)
	}
}

// An event Cline has no file name for is a note, not a file: nothing
// scans for a name outside HookConfigFileName, so writing one would be
// a silent drop.
func TestEmit_Hook_UnknownEventNotesInsteadOfWriting(t *testing.T) {
	dir := testutil.TempCwd(t)
	buf := swapNoteWarner(t)

	entries := []spec.Entry{
		{Kind: spec.KindHook, Name: "h", Meta: map[string]any{"event": "SessionStart", "command": "echo hi"}},
	}
	if err := New().Emit(emit.NewSession(), spec.NewBundle(entries), &config.Config{}, false); err != nil {
		t.Fatalf("emit: %v", err)
	}
	emit.FlushCoverageNotes()

	if _, err := os.Stat(filepath.Join(dir, ".cline/hooks")); !os.IsNotExist(err) {
		t.Errorf("expected no hooks dir for an unreadable event; err=%v", err)
	}
	if !strings.Contains(buf.String(), "Cline reads a hook by file name") {
		t.Errorf("expected an unknown-event note, got: %q", buf.String())
	}
}


func swapNoteWarner(t *testing.T) *strings.Builder {
	t.Helper()
	buf := &strings.Builder{}
	prev := emit.Warner
	emit.Warner = buf
	t.Cleanup(func() { emit.Warner = prev })
	emit.ResetCoverageNotes()
	t.Cleanup(emit.ResetCoverageNotes)
	return buf
}

// Cline discovers a hook by file name: `toHookConfigFileName` strips
// the extension, lowercases the stem and looks it up in
// HOOK_CONFIG_FILE_LOOKUP (hook-file-config.ts). So the event has to be
// the file name, `.sh` has to be in SUPPORTED_HOOK_FILE_EXTENSIONS, and
// the script has to be executable.
func TestEmit_Hook_WritesOneExecutableScriptPerEvent(t *testing.T) {
	dir := testutil.TempCwd(t)

	entries := []spec.Entry{
		{
			Kind: spec.KindHook, Name: "fmt-go",
			Meta: map[string]any{"event": "PostToolUse", "command": "gofmt -w ."},
		},
		{
			Kind: spec.KindHook, Name: "greet",
			Meta: map[string]any{"event": "TaskStart", "command": "echo start"},
		},
	}
	if err := New().Emit(emit.NewSession(), spec.NewBundle(entries), &config.Config{}, false); err != nil {
		t.Fatalf("emit: %v", err)
	}

	for path, want := range map[string]string{
		".cline/hooks/PostToolUse.sh": "gofmt -w .",
		".cline/hooks/TaskStart.sh":   "echo start",
	} {
		full := filepath.Join(dir, path)
		got, err := os.ReadFile(full)
		if err != nil {
			t.Fatalf("read %s: %v", path, err)
		}
		if !strings.Contains(string(got), want) {
			t.Errorf("%s missing %q:\n%s", path, want, got)
		}
		if !strings.HasPrefix(string(got), "# Generated by agnostic-ai") {
			t.Errorf("%s must open with the provenance comment, got:\n%s", path, got)
		}
		// A shebang would have to sit above the provenance line, which
		// would stop sync recognizing the file as managed. `.sh` runs
		// under bash through inferHookCommand without one.
		if strings.Contains(string(got), "#!") {
			t.Errorf("%s must carry no shebang:\n%s", path, got)
		}
		info, err := os.Stat(full)
		if err != nil {
			t.Fatalf("stat %s: %v", path, err)
		}
		// Windows has no POSIX execute bit: Go reports 0o666 for every
		// file it writes there, so this assertion can only hold on
		// unix. Emission still chmods, and Cline runs a `.sh` hook as
		// `bash <path>` via inferHookCommand, which needs no exec bit
		// on any platform.
		if runtime.GOOS != "windows" && info.Mode().Perm()&0o100 == 0 {
			t.Errorf("%s must be executable, mode = %v", path, info.Mode().Perm())
		}
	}
}

// HOOK_CONFIG_FILE_LOOKUP is keyed by the lowercased enum value, so
// Cline itself accepts any casing of a file name. Fold the spec's
// `event:` the same way instead of dropping a spelling Cline reads.

package codex

import (
	"fmt"
	"os"
	"strings"

	"github.com/chemaclass/agnostic-ai/internal/adapters/internal/emit"
	"github.com/chemaclass/agnostic-ai/internal/config"
	"github.com/chemaclass/agnostic-ai/internal/spec"
)

type Adapter struct{}

func New() *Adapter { return &Adapter{} }

func (a *Adapter) Name() string { return "codex" }

func (a *Adapter) Emit(entries []spec.Entry, cfg *config.Config, dryRun bool) error {
	var b strings.Builder
	b.WriteString("# AGENTS.md\n\nGenerated by agnostic-ai. Do not edit by hand.\n\n")

	if rules := spec.Filter(entries, spec.KindRule); len(rules) > 0 {
		b.WriteString("## Rules\n\n")
		for _, r := range rules {
			b.WriteString("### " + r.Name + "\n\n" + r.Body + "\n\n")
		}
	}
	if agents := spec.Filter(entries, spec.KindAgent); len(agents) > 0 {
		b.WriteString("## Agents\n\n")
		for _, ag := range agents {
			b.WriteString("### " + ag.Name + "\n\n" + ag.Body + "\n\n")
		}
	}

	if len(spec.Filter(entries, spec.KindHook)) > 0 {
		fmt.Fprintln(os.Stderr, "  ! codex: hooks not supported, skipped")
	}
	if len(spec.Filter(entries, spec.KindSkill)) > 0 {
		fmt.Fprintln(os.Stderr, "  ! codex: skills not supported, skipped")
	}

	out := "AGENTS.md"
	if o, ok := cfg.Outputs["codex"]; ok && o.File != "" {
		out = o.File
	}
	return emit.WriteFile(out, b.String(), dryRun)
}

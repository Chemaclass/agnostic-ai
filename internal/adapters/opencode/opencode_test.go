// Unrelated frontmatter keys (and the x- nested map itself) don't leak
// into the command frontmatter.
func TestEmit_Agent_OnlyAllowedFrontmatterKeys(t *testing.T) {
	dir := testutil.TempCwd(t)

	entries := []spec.Entry{
		{
			Kind: spec.KindAgent,
			Name: "ag",
			Meta: map[string]any{
				"description": "x",
				"name":        "ag",
				"globs":       "src/**",
				"tools":       []any{"Read"},
				"x-opencode":  map[string]any{"mode": "subagent"},
			},
			Body: "body",
		},
	}
	if err := New().Emit(spec.NewBundle(entries), &config.Config{}, false); err != nil {
		t.Fatal(err)
	}
	got := readFile(t, filepath.Join(dir, ".opencode/agents/ag.md"))
	for _, leaked := range []string{"globs:", "tools:", "name:", "x-opencode:"} {
		if strings.Contains(got, leaked) {
			t.Errorf("unexpected leaked frontmatter %q in %s", leaked, got)
		}
	}
}


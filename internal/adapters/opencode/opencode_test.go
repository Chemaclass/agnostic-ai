// Command specs emit one markdown file per command under
// .opencode/commands/, the native slash-prompt surface.
func TestEmit_WritesCommandFile(t *testing.T) {
	dir := testutil.TempCwd(t)
	b := spec.NewBundle([]spec.Entry{
		{Kind: spec.KindCommand, Name: "deploy", Path: "commands/deploy.md", Meta: map[string]any{"description": "Ship it"}, Body: "Run the deploy steps."},
	})
	if err := New().Emit(b, &config.Config{}, false); err != nil {
		t.Fatalf("emit: %v", err)
	}
	data, err := os.ReadFile(filepath.Join(dir, ".opencode", "commands", "deploy.md"))
	if err != nil {
		t.Fatalf("read command file: %v", err)
	}
	got := string(data)
	for _, want := range []string{"description: Ship it", "Run the deploy steps.", "Generated by agnostic-ai"} {
		if !strings.Contains(got, want) {
			t.Errorf("command file missing %q:\n%s", want, got)
		}
	}
}


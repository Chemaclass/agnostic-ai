package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"text/template"

	"github.com/chemaclass/agnostic-ai/internal/adapters"
	"github.com/chemaclass/agnostic-ai/internal/config"
)

func main() {
	check := flag.Bool("check", false, "fail when generated site data is stale")
	flag.Parse()
	if err := generate("docs/site", adapters.Names(), config.DefaultTargets(), *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(root string, supported, defaults []string, check bool) error {
	counts := struct {
		Supported int
		Default   int
	}{len(supported), len(defaults)}
	source := filepath.Join(root, "llms.txt.tmpl")
	tmpl, err := template.ParseFiles(source)
	if err != nil {
		return fmt.Errorf("parse %s: %w", source, err)
	}
	var llms bytes.Buffer
	if err := tmpl.Execute(&llms, counts); err != nil {
		return fmt.Errorf("render %s: %w", source, err)
	}
	data := fmt.Sprintf("# Generated by go run ./cmd/sitegen. Do not edit.\nsupported = %d\ndefault = %d\n", counts.Supported, counts.Default)
	for _, output := range []struct {
		path string
		body []byte
	}{
		{"data/targets.toml", []byte(data)},
		{"static/llms.txt", llms.Bytes()},
	} {
		path := filepath.Join(root, output.path)
		if check {
			current, err := os.ReadFile(path)
			if err != nil {
				return fmt.Errorf("%s: %w; run make site-generate", path, err)
			}
			if !bytes.Equal(current, output.body) {
				return fmt.Errorf("%s: generated output is stale; run make site-generate", path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return fmt.Errorf("%s: %w", filepath.Dir(path), err)
		}
		if err := os.WriteFile(path, output.body, 0o644); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
	}
	return nil
}
